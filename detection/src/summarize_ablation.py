"""Build the arm A / B / C comparison table from the downloaded run folders.

Run (from the repository root):
    python detection/src/summarize_ablation.py

Reads runs/m2_*_arm{A,B,C}_seed*/M2_results_for_report.md (the reports the pipeline writes; run folders are not in git)
and writes
    detection/results/ablation/README.md       mean ± sample std over the seeds of each arm, then one row per run
    detection/results/ablation/runs/<run>.md   a copy of every run's report, so the numbers stay in git
Arms: A = D1 grid composites (1,500), B = D1 750–1499 + 750 D3 copy-paste images, C = D3 only (1,500); same objects,
60 epochs without early stopping, checkpoint and threshold chosen on D1-val + hard-val.
"""
import re
import shutil
import statistics as st
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RUNS = REPO / "runs"
OUT = REPO / "detection" / "results" / "ablation"
ARMS = {"A": "arm A (D1)", "B": "arm B (D1+D3)", "C": "arm C (D3)"}
SETS = ["D1-val", "hard-val", "D1-test", "T-hard"]


def parse(md):
    r = {}
    for s in SETS:          # | set | mAP@0.5 | mAP@0.5:0.95 | precision | recall | macro-F1 |
        m = re.search(rf"^\| (?:\*\*)?{re.escape(s)}(?:\*\*)? \| ([0-9.]+) \| ([0-9.]+) \| ([0-9.]+) \| ([0-9.]+) \| ([0-9.]+) \|",
                      md, re.M)
        r[f"{s} mAP50"], r[f"{s} mAP50-95"], r[f"{s} F1"] = float(m.group(1)), float(m.group(2)), float(m.group(5))
    r["val_score"] = float(re.search(r"val_score .*?= ([0-9]+.[0-9]+)", md).group(1))
    r["threshold"] = float(re.search(r"General threshold ([0-9.]+)", md).group(1))
    r["single-object test photos /303"] = int(re.search(r"Single-object test images through the detector: (\d+)/303", md).group(1))
    r["single-object val photos /303"] = int(re.search(r"Single-object val photos .*?: (\d+)/303", md).group(1))
    r["OBJ001 AP50 (D1-test)"] = float(re.search(r"^\| OBJ001 \| ([0-9.]+) \|", md[md.index("### Per-class (D1-test)"):], re.M).group(1))
    t = re.search(r"\(best (\d+)\), ([0-9.]+) min on (.+?);", md)
    r["best epoch"], r["minutes"], r["gpu"] = int(t.group(1)), float(t.group(2)), t.group(3)
    return r


def main():
    res = {}
    (OUT / "runs").mkdir(parents=True, exist_ok=True)
    for d in sorted(RUNS.glob("m2_*_arm*_seed*")):
        m = re.search(r"arm([ABC])_seed(\d+)$", d.name)
        rep = d / "M2_results_for_report.md"
        res[(m.group(1), int(m.group(2)))] = dict(parse(rep.read_text(encoding="utf-8")), run=d.name)
        shutil.copy2(rep, OUT / "runs" / f"{d.name}.md")
    arms = [a for a in ARMS if any(k[0] == a for k in res)]
    metrics = [k for k in next(iter(res.values())) if k not in ("run", "threshold", "best epoch", "minutes", "gpu")]
    seeds = {a: sorted((s for b, s in res if b == a), key=lambda s: (s != 42, s)) for a in arms}
    out = ["# D1 vs D1+D3 vs D3: replacement ablation", "",
           "Generated by `detection/src/summarize_ablation.py` from the run reports in [`runs/`](runs/). "
           "Mean ± sample std over training seeds " + ", ".join(f"{a}: {'/'.join(map(str, seeds[a]))}" for a in arms) + ".", "",
           "- **arm A:** 1,500 D1 grid composites", "- **arm B:** D1 images 750–1499 + 750 D3 copy-paste images built from the "
           "objects of the D1 images they replace", "- **arm C:** 1,500 D3 images built from the objects of all 1,500 D1 images",
           "- All arms: same objects and instance counts, YOLOv8n, 60 epochs without early stopping, checkpoint and threshold "
           "chosen on D1-val + hard-val. hard-val and T-hard are D3-style synthetic sets on the gray canvas, so they favour "
           "arms B and C; the real-photo results are in [`../real_photos/`](../real_photos/README.md).", "",
           "| metric | " + " | ".join(ARMS[a] for a in arms) + " |", "|---|" + "---|" * len(arms)]
    for k in metrics:
        p = 1 if "/303" in k else 3
        cells = []
        for a in arms:
            v = [res[(a, s)][k] for s in seeds[a]]
            cells.append(f"{st.mean(v):.{p}f} ± {st.stdev(v):.{p}f}" if len(v) > 1 else f"{v[0]:.{p}f}")
        out.append(f"| {k} | " + " | ".join(cells) + " |")
    out += ["", "## Per run", "", "| run | arm | seed | threshold | best epoch | GPU, minutes | D1-test mAP50 | T-hard mAP50 | val_score |",
            "|---|---|---|---|---|---|---|---|---|"]
    for a in arms:
        for s in seeds[a]:
            r = res[(a, s)]
            out.append(f"| [{r['run']}](runs/{r['run']}.md) | {a} | {s} | {r['threshold']} | {r['best epoch']} | "
                       f"{r['gpu']}, {r['minutes']} | {r['D1-test mAP50']:.3f} | {r['T-hard mAP50']:.3f} | {r['val_score']:.3f} |")
    (OUT / "README.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'README.md'} ({len(res)} runs)")


if __name__ == "__main__":
    main()
